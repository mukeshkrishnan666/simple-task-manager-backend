package com.mukesh.taskmanager.repository;

import com.mukesh.taskmanager.model.Task;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;

import static org.junit.jupiter.api.Assertions.*;

@DataJpaTest
class TaskRepositoryTest {

    @Autowired
    private TaskRepository taskRepository;

    @Test
    void givenTaskEntity_whenSave_thenGenerateIdAndCreatedAt() {
        // Given
        Task task = Task.builder()
                .title("Database Task")
                .description("Testing JPA Persist")
                .build();

        // When
        Task savedTask = taskRepository.save(task);

        // Then
        assertNotNull(savedTask.getId(), "Primary key ID should be auto-generated");
        assertEquals("Database Task", savedTask.getTitle());
        assertNotNull(savedTask.getCreatedAt(), "CreatedAt timestamp should be auto-generated by @PrePersist");
    }
}
